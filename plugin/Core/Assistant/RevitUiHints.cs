        /// <summary>Пояснение к кнопке или null. Сначала по Id, потом по подписи.</summary>
        public static Hint For(string commandId, string caption)
        {
            if (!string.IsNullOrWhiteSpace(commandId))
            {
                var byId = All.FirstOrDefault(h =>
                    h.Ids.Any(id => id.Equals(commandId, StringComparison.OrdinalIgnoreCase)));
                if (byId != null)
                    return byId;
            }

            if (string.IsNullOrWhiteSpace(caption))
                return null;

            var text = caption.ToLowerInvariant();
            return All.FirstOrDefault(h => h.Captions.Any(c => text.Contains(c)));
        }
